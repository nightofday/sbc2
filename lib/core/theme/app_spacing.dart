/// The spacing scale: 8, 16, 24, 32 and 48, plus 4 for the tightest gaps
/// such as between a label and its value. Use these names rather than
/// numbers for gaps, padding and margins.
class AppSpacing {
  const AppSpacing._();

  static const double xs = 4;
  static const double sm = 8;
  static const double md = 16;
  static const double lg = 24;
  static const double xl = 32;
  static const double xxl = 48;

  /// Space between a page's edge and its content on a tablet or desktop.
  static const double page = 24;
  static const double sidebarWidth = 220;
}
